"""Compare original and minimal IK on an actually contact-held fixture.

The fixture is generated by native actuators, without measured planning waits.
These checks prove numerical/pipeline agreement, not complete task performance.
"""
import copy
import time
import unittest

import mujoco
import numpy as np

from harness.object_handover import ProtectedObjectEnv
from sim.bottle_routing import BottleHandoverPlanner
from sim.fast_handover import FastBottleHandover
from sim.margin_grasp import MarginBottlePick
from sim.tamp import PlanningFailure
from tools.check_bottle_routes import initialize


class HandoverIKChecks(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.env=ProtectedObjectEnv(images=False)
        case={'name':'cross-relay-a','arm':'left','receiver':'right',
            'origin_xy_m':[.525,-.2],'target_xy_m':[.57,-.09]}
        initialize(cls.env,case)
        p=MarginBottlePick(cls.env,'pick_object',parameters={'object_id':'bottle',
            'arm':'left','next_handover':{'to_arm':'right'}})
        for action,diagnostic in p.actions():
            _,_,term,trunc,_=cls.env.step_tamp(action)
            if term or trunc:raise AssertionError('native grasp fixture ended')
        if not p.result.get('primitive_success') or not cls.env.evaluation['held']['left']:
            raise AssertionError('contact-held donor fixture required')
        print('fixture: actual native left contact and lift, paused planning, synthetic start',flush=True)
    @classmethod
    def tearDownClass(cls):cls.env.close()
    def setUp(self):
        env=self.env
        self.before=(env.data.qpos.copy(),env.data.qvel.copy(),env.data.ctrl.copy(),
            env.data.xpos.copy(),env.data.time,copy.deepcopy(env.evaluation),env.manifest()['model_evidence'])
    def check_live(self):
        env=self.env
        for before,after in zip(self.before[:4],(env.data.qpos,env.data.qvel,env.data.ctrl,env.data.xpos)):
            np.testing.assert_array_equal(before,after)
        self.assertEqual(self.before[4],env.data.time);self.assertEqual(self.before[5],env.evaluation)
        self.assertEqual(self.before[6],env.manifest()['model_evidence'])
    def planners(self,side):
        values=[]
        for factory in (BottleHandoverPlanner,FastBottleHandover):
            p=factory(self.env,'handover_object',parameters={'object_id':'bottle',
                'from_arm':'left','to_arm':'right','next_place':{'surface':'table','target_xy_m':[.57,-.09]}})
            p._arm(side,side=='left');p._sync();p.rotation=p._pose()[1].copy()
            values.append(p)
        return values
    def test_carried_and_empty_hand_pose_jacobian_and_full_collision_agree(self):
        env=self.env
        for side in ('left','right'):
            full,fast=self.planners(side);fast._kinematics_only=True
            for delta in (0.,.009,-.014):
                q=env.data.qpos[env.qids[side]].copy();q[2]+=delta
                full._at(q);fast._at(q)
                for a,b in zip(full._pose(),fast._pose()):np.testing.assert_array_equal(a,b)
                np.testing.assert_array_equal(full.data.xpos,fast.data.xpos)
                for planner in (full,fast):
                    jac=np.zeros((3,env.model.nv));point=planner._pose()[0]
                    mujoco.mj_jac(env.model,planner.data,jac,None,point,planner.body)
                    planner._test_jac=jac
                np.testing.assert_array_equal(full._test_jac,fast._test_jac)
                for fingers in (False,True):
                    self.assertEqual(full._collision(q,fingers),fast._collision(q,fingers))
                    self.assertEqual(full.last_collision,fast.last_collision)
                    self.assertEqual(full.data.ncon,fast.data.ncon)
                self.assertTrue(fast._kinematics_only)
        self.check_live()
    def test_same_solver_results_and_native_failure_codes_are_preserved(self):
        timings={'full':[],'minimal':[]}
        for side in ('left','right'):
            for unreachable in (False,True):
                full,fast=self.planners(side);target=full._pose()[0].copy()+[2. if unreachable else 0.,0.,.006]
                values=[]
                for name,p in (('full',full),('minimal',fast)):
                    started=time.monotonic()
                    try:values.append(p._ik(target,side=='left'))
                    except PlanningFailure as exc:values.append(exc.code)
                    timings[name].append(time.monotonic()-started)
                if isinstance(values[0],str):self.assertEqual(values[0],values[1])
                else:np.testing.assert_array_equal(*values)
                self.assertFalse(getattr(fast,'_kinematics_only',False))
        print('paired handover IK seconds',timings,flush=True)
        self.check_live()
    def test_cancellation_restores_pipeline_flag_and_saves_private_trace(self):
        _,fast=self.planners('left');fast.cancel=lambda:True
        with self.assertRaises(PlanningFailure) as error:fast._ik(fast._pose()[0].copy(),True)
        self.assertEqual(error.exception.code,'cancelled');self.assertFalse(fast._kinematics_only)
        self.assertEqual(fast.result['private_search_progress']['IK_failures']['cancelled'],1)
        self.assertNotIn('primitive_success',fast.result);self.check_live()


if __name__=='__main__':unittest.main()
