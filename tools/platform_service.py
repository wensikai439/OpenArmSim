#!/usr/bin/env python3
"""On-demand user service; independent of Codex command/session lifetime."""
import argparse
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile
import time
import urllib.error
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
UNIT = 'openarm-sim.service'
SOURCE = ROOT / 'tools' / UNIT
URL = 'http://127.0.0.1:8767'
MANAGED_MARKER = '# Generated by OpenArmSim; do not edit this file.'


def systemd_quote(value):
    """Escape a systemd path/value without invoking a shell."""
    value = str(value)
    if any(char in value for char in '\r\n\0'):
        raise RuntimeError('systemd 路径包含不支持的控制字符。')
    return (value.replace('\\', r'\x5c').replace(' ', r'\x20')
            .replace('\t', r'\x09').replace('"', r'\x22').replace('%', '%%'))


def render_unit(source):
    replacements = {
        '@OPENARMSIM_ROOT@': systemd_quote(ROOT),
        '@OPENARMSIM_PYTHON@': systemd_quote(ROOT / '.venv' / 'bin' / 'python'),
        '@OPENARMSIM_POLICY@': systemd_quote(ROOT / 'harness' / 'policy.json'),
        '@OPENARMSIM_ACT_CHECKPOINT@': systemd_quote(ROOT / 'models' / 'act' / 'checkpoint' / 'model.safetensors'),
        '@OPENARMSIM_CUROBO_PYTHON@': systemd_quote(ROOT / '.runtime' / 'curobo' / 'bin' / 'python'),
        '@OPENARMSIM_CUROBO_PRESENT@': systemd_quote(ROOT / '.runtime' / 'curobo' / 'bin' / 'python'),
    }
    rendered = source.read_text(encoding='utf-8')
    for placeholder, value in replacements.items():
        rendered = rendered.replace(placeholder, value)
    if '@OPENARMSIM_' in rendered:
        raise RuntimeError(f'{source.name} 存在未解析的路径配置。')
    return MANAGED_MARKER + '\n' + rendered


def systemctl(*args, check=True, capture=False):
    return subprocess.run(['systemctl', '--user', *args], check=check,
                          capture_output=capture, text=True)


def install():
    directory = Path(os.environ.get('XDG_CONFIG_HOME', Path.home() / '.config')) / 'systemd' / 'user'
    directory.mkdir(parents=True, exist_ok=True)
    rendered_units = []
    for unit in (UNIT, 'openarm-act.service', 'openarm-curobo.service'):
        source = ROOT / 'tools' / unit
        target = directory / unit
        rendered = render_unit(source)
        if target.is_symlink() and target.resolve() != source.resolve():
            raise RuntimeError(f'{target} 已属于其他服务，未修改。')
        if target.exists() and not target.is_symlink():
            try:
                existing = target.read_text(encoding='utf-8')
            except (OSError, UnicodeError) as error:
                raise RuntimeError(f'{target} 已存在且无法识别，未修改。') from error
            if MANAGED_MARKER not in existing:
                raise RuntimeError(f'{target} 已属于其他服务，未修改。')
        rendered_units.append((target, rendered))
    for target, rendered in rendered_units:
        if target.is_symlink():
            target.unlink()
        temporary = None
        try:
            with tempfile.NamedTemporaryFile(mode='w', encoding='utf-8', dir=directory,
                                             prefix=f'.{target.name}.', delete=False) as stream:
                temporary = Path(stream.name)
                stream.write(rendered)
            os.chmod(temporary, 0o644)
            os.replace(temporary, target)
        finally:
            if temporary is not None and temporary.exists():
                temporary.unlink()
    systemctl('daemon-reload')


def status_json():
    with urllib.request.urlopen(URL + '/api/status', timeout=2) as response:
        return json.load(response)


def health_json():
    with urllib.request.urlopen(URL + '/health', timeout=2) as response:
        return json.load(response)


def ready():
    try:
        status = health_json()
        return (status.get('state') in {'ready', 'running'}
                and status.get('backend') == 'native-mujoco'
                and status.get('source_current', True) is True)
    except (OSError, urllib.error.URLError, ValueError):
        return False


def main():
    parser = argparse.ArgumentParser(description='按需启动、停止或查看 OpenArm 平台服务')
    parser.add_argument('command', choices=['start', 'stop', 'status', 'logs'])
    args = parser.parse_args()
    if args.command == 'logs':
        return subprocess.call(['journalctl', '--user', '-u', UNIT, '-n', '50', '--no-pager'])
    if args.command == 'status':
        active = systemctl('is-active', UNIT, check=False, capture=True)
        try:
            health = health_json()
            status = status_json()
        except (OSError, urllib.error.URLError, ValueError):
            health, status = {}, {}
        is_ready = ready()
        print(f'服务：{active.stdout.strip() or "未安装"}；页面：{URL}/；状态：{health.get("state", "不可达")}；就绪：{is_ready}')
        if health.get('source_current') is False:
            print('源码版本已变化；停止新工具调用并重启服务。')
        workers = status.get('model_workers', {})
        if workers.get('act', {}).get('reason'):
            print(f'ACT：{workers["act"]["reason"]}')
        if workers.get('curobo', {}).get('reason'):
            print(f'cuRobo：{workers["curobo"]["reason"]}')
        return 0 if active.returncode == 0 and is_ready else 1
    if args.command == 'start':
        overrides = [name for name in ('OPENARM_POLICY_CONFIG', 'OPENARM_LLM_BASE', 'OPENARM_LLM_MODEL',
                                       'OPENARM_LLM_KEY', 'OPENARM_LLM_VISION', 'CUDA_VISIBLE_DEVICES')
                     if name in os.environ]
        if overrides or os.environ.get('MUJOCO_GL', 'egl') != 'egl':
            raise RuntimeError('持久服务不继承终端的模型/渲染环境设置。此类启动请使用 ./run serve；API 可在页面保存。')
    install()
    if args.command == 'stop':
        systemctl('stop', UNIT)
        print('平台已停止，睡眠保护已释放。')
        return 0
    if os.environ.get('OPENARM_PORT', '8767') != '8767':
        raise RuntimeError('工作台服务固定使用 8767；旧版入口可用 OPENARM_PORT=端口 ./run serve。')
    active = systemctl('is-active', UNIT, check=False, capture=True).returncode == 0
    if not active and ready():
        raise RuntimeError('已有前台服务占用 8767；请先结束该服务，再使用 ./run 启动持久服务。')
    systemctl('reset-failed', UNIT, 'openarm-act.service', 'openarm-curobo.service', check=False)
    systemctl('start', UNIT)
    deadline = time.monotonic() + 25
    while time.monotonic() < deadline:
        if ready():
            print(f'OpenArm Lab: {URL}/')
            print('持久服务已就绪；运行期间保持系统清醒。停止：./run stop；状态：./run status')
            return 0
        state = systemctl('is-active', UNIT, check=False, capture=True).stdout.strip()
        if state not in {'active', 'activating'}:
            raise RuntimeError('服务未启动成功；运行 ./run logs 查看原因。')
        time.sleep(.3)
    raise RuntimeError('服务仍在启动，未强制重启；使用 ./run status 或 ./run logs 查看状态。')


if __name__ == '__main__':
    try:
        sys.exit(main())
    except (RuntimeError, subprocess.CalledProcessError) as error:
        print(str(error), file=sys.stderr)
        sys.exit(1)
